// Command tamamo-build builds a tamamo binary that contains extra modules.
//
//	tamamo-build --with github.com/you/tamamo-geo
//	tamamo-build --with github.com/you/tamamo-geo@v1.2.0 --with example.com/other -o ./tamamo
//	tamamo-build --with github.com/you/tamamo-geo=../tamamo-geo   # a module on your disk
//
// It writes a three-line main package that imports Tamamo and the modules
// into a temporary folder and runs "go build" there, so it needs the Go
// toolchain. Every --with value is a Go module path, optionally followed by
// @version or by =<folder> to use a local copy.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
)

const corePath = "github.com/foxgirlsorg/tamamo"

// dep is one --with value.
type dep struct {
	path    string // Go module path
	pkg     string // package to import (the path unless it names a sub-package)
	version string // "" = latest
	replace string // local folder, or ""
}

type deps []dep

func (d *deps) String() string { return fmt.Sprint(*d) }

func (d *deps) Set(v string) error {
	dp, err := parseDep(v)
	if err != nil {
		return err
	}
	*d = append(*d, dp)
	return nil
}

// parseDep reads "path[@version][=folder]".
func parseDep(v string) (dep, error) {
	var d dep
	v = strings.TrimSpace(v)
	if i := strings.Index(v, "="); i >= 0 {
		d.replace = strings.TrimSpace(v[i+1:])
		v = v[:i]
		if d.replace == "" {
			return d, errors.New("nothing after \"=\"; write path=../folder")
		}
	}
	if i := strings.Index(v, "@"); i >= 0 {
		d.version = v[i+1:]
		v = v[:i]
	}
	d.path = strings.TrimSuffix(strings.TrimSpace(v), "/")
	d.pkg = d.path
	if d.path == "" || strings.ContainsAny(d.path, " \t\"'`\\") || !strings.Contains(d.path, "/") {
		return d, fmt.Errorf("%q is not a Go module path like github.com/you/tamamo-geo", v)
	}
	return d, nil
}

func main() {
	var with deps
	flag.Var(&with, "with", "Go `module` to compile in: path[@version][=local folder]. Repeat for more.")
	out := flag.String("o", defaultOutput(), "where to write the binary")
	core := flag.String("tamamo", "", "Tamamo `version` to build (e.g. v1.0.1 or a commit), or a folder with its source. Default: the latest release")
	keep := flag.Bool("keep", false, "keep the temporary build folder and print where it is")
	flag.Usage = func() {
		fmt.Fprintln(os.Stderr, "tamamo-build builds tamamo with extra modules compiled in.")
		fmt.Fprintln(os.Stderr, "\nUsage: tamamo-build [flags]")
		flag.PrintDefaults()
		fmt.Fprintln(os.Stderr, "\nExamples:")
		fmt.Fprintln(os.Stderr, "  tamamo-build --with github.com/you/tamamo-geo")
		fmt.Fprintln(os.Stderr, "  tamamo-build --with github.com/you/tamamo-geo=../tamamo-geo --tamamo ../tamamo -o ./tamamo")
	}
	flag.Parse()
	if flag.NArg() > 0 {
		fmt.Fprintln(os.Stderr, "tamamo-build: unexpected argument", flag.Arg(0))
		flag.Usage()
		os.Exit(2)
	}
	if err := build(with, *out, *core, *keep); err != nil {
		fmt.Fprintln(os.Stderr, "tamamo-build:", err)
		os.Exit(1)
	}
}

func defaultOutput() string {
	if runtime.GOOS == "windows" || os.Getenv("GOOS") == "windows" {
		return "tamamo.exe"
	}
	return "tamamo"
}

// mainSource is the generated main package.
func mainSource(with []dep) string {
	var b strings.Builder
	b.WriteString("// Code generated by tamamo-build. DO NOT EDIT.\npackage main\n\nimport (\n")
	fmt.Fprintf(&b, "\t%q\n", corePath+"/app")
	if len(with) > 0 {
		b.WriteString("\n")
	}
	for _, d := range with {
		fmt.Fprintf(&b, "\t_ %q\n", d.pkg)
	}
	b.WriteString(")\n\nfunc main() { app.Main() }\n")
	return b.String()
}

func build(with []dep, out, core string, keep bool) error {
	if _, err := exec.LookPath("go"); err != nil {
		return errors.New("the Go toolchain is needed (https://go.dev/dl/), or use the Docker build: docker build --build-arg MODULES=\"...\" .")
	}
	outAbs, err := filepath.Abs(out)
	if err != nil {
		return err
	}
	dir, err := os.MkdirTemp("", "tamamo-build-")
	if err != nil {
		return err
	}
	if keep {
		fmt.Println("build folder:", dir)
	} else {
		defer os.RemoveAll(dir)
	}
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(mainSource(with)), 0o644); err != nil {
		return err
	}
	run := func(args ...string) error {
		fmt.Println("go", strings.Join(args, " "))
		cmd := exec.Command("go", args...)
		cmd.Dir = dir
		cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
		// Static binary, like the official builds.
		cmd.Env = append(os.Environ(), "CGO_ENABLED=0")
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("go %s: %w", args[0], err)
		}
		return nil
	}
	if err := run("mod", "init", "tamamo-custom"); err != nil {
		return err
	}

	// The core: a folder (replace) or a version (get).
	coreGet := corePath + "@latest"
	if core != "" {
		if fi, err := os.Stat(core); err == nil && fi.IsDir() {
			abs, err := filepath.Abs(core)
			if err != nil {
				return err
			}
			if err := run("mod", "edit", "-require="+corePath+"@v0.0.0", "-replace="+corePath+"="+abs); err != nil {
				return err
			}
			coreGet = ""
		} else {
			coreGet = corePath + "@" + core
		}
	}
	if coreGet != "" {
		if err := run("get", coreGet); err != nil {
			return err
		}
	}
	for _, d := range with {
		if d.replace != "" {
			abs, err := filepath.Abs(d.replace)
			if err != nil {
				return err
			}
			if fi, err := os.Stat(abs); err != nil || !fi.IsDir() {
				return fmt.Errorf("--with %s: %s is not a folder", d.path, d.replace)
			}
			if err := run("mod", "edit", "-require="+d.path+"@v0.0.0", "-replace="+d.path+"="+abs); err != nil {
				return err
			}
			continue
		}
		v := d.version
		if v == "" {
			v = "latest"
		}
		if err := run("get", d.path+"@"+v); err != nil {
			return err
		}
	}
	if err := run("mod", "tidy"); err != nil {
		return err
	}
	if err := run("build", "-trimpath", "-ldflags=-s -w", "-o", outAbs, "."); err != nil {
		return err
	}
	fmt.Println("built", outAbs)
	fmt.Println("check what it contains with:", outAbs, "-modules")
	return nil
}
